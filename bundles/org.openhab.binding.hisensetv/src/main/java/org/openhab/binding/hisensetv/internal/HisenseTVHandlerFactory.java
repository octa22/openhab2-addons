package org.openhab.binding.hisensetv.internal;

import org.eclipse.jdt.annotation.NonNullByDefault;
import org.eclipse.jdt.annotation.Nullable;
import org.openhab.core.thing.Thing;
import org.openhab.core.thing.ThingTypeUID;
import org.openhab.core.thing.binding.BaseThingHandlerFactory;
import org.openhab.core.thing.binding.ThingHandler;
import org.openhab.core.thing.binding.ThingHandlerFactory;
import org.osgi.service.component.annotations.Component;

/**
 * The {@link HisenseTVHandlerFactory} is responsible for creating things and thing
 * handlers.
 *
 * @author Ondrej Pecta - Initial contribution
 */
@NonNullByDefault
@Component(configurationPid = "binding.hisensetv", service = ThingHandlerFactory.class)
public class HisenseTVHandlerFactory extends BaseThingHandlerFactory {

    private static final ThingTypeUID TV = new ThingTypeUID("hisensetv", "tv");

    @Override
    public boolean supportsThingType(ThingTypeUID thingTypeUID) {
        return TV.equals(thingTypeUID);
    }

    @Override
    protected @Nullable ThingHandler createHandler(Thing thing) {
        return supportsThingType(thing.getThingTypeUID()) ? new HisenseTVHandler(thing) : null;
    }
}
